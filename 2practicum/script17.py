# Считываем три числа, введенные через пробел
N, K, M = map(int, input().split())

# Вариант 1: Движение «напрямую» (абсолютная разница между станциями)
path1 = abs(K - M) - 1

# Вариант 2: Движение в противоположную сторону («через край» кольца)
path2 = N - abs(K - M) - 1

# Находим и выводим минимальное количество станций
print(min(path1, path2))
